create database goaldb;

BEGIN;

DO $$
    BEGIN
        CREATE TYPE pix_key_type AS ENUM (
            'CPF',
            'CNPJ',
            'Phone',
            'Email',
            'Random'
            );
    EXCEPTION
        WHEN duplicate_object THEN NULL;
    END
$$;

DO $$
    BEGIN
        CREATE TYPE group_member_role AS ENUM (
            'CAN_CREATE_DEBT',
            'CANNOT_CREATE_DEBT'
            );
    EXCEPTION
        WHEN duplicate_object THEN NULL;
    END
$$;

CREATE TABLE IF NOT EXISTS auditable_entity (
                                                created_by VARCHAR(150) NOT NULL,
                                                created_at TIMESTAMP NOT NULL,
                                                updated_by VARCHAR(150),
                                                updated_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS users (
                                     id SERIAL PRIMARY KEY,
                                     first_name VARCHAR(100) NOT NULL,
                                     last_name VARCHAR(100) NOT NULL,
                                     birth_date DATE,
                                     email VARCHAR(255) NOT NULL,
                                     password_hash TEXT NOT NULL
) INHERITS (auditable_entity);

CREATE TABLE IF NOT EXISTS groups (
                                              id SERIAL PRIMARY KEY,
                                              name VARCHAR(255)
) INHERITS (auditable_entity);

CREATE TABLE IF NOT EXISTS banks (
                                     id SERIAL PRIMARY KEY,
                                     name VARCHAR(150) NOT NULL
) INHERITS (auditable_entity);

CREATE TABLE IF NOT EXISTS group_expenses (
                                              id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                              subject VARCHAR(255) NOT NULL,
                                              total_amount NUMERIC NOT NULL,
                                              group_id INTEGER NOT NULL
                                                  CONSTRAINT fk_group_expenses_group
                                                      REFERENCES groups (id)
                                                      ON DELETE NO ACTION ON UPDATE NO ACTION,
                                              user_id INTEGER NOT NULL
                                                  CONSTRAINT fk_group_user
                                                      REFERENCES users (id)
                                                      ON DELETE NO ACTION ON UPDATE NO ACTION
) INHERITS (auditable_entity);

CREATE TABLE IF NOT EXISTS user_debts (
                                          id SERIAL PRIMARY KEY,
                                          amount NUMERIC NOT NULL,
                                          user_id INTEGER NOT NULL
                                              CONSTRAINT fk_user_debts_user
                                                  REFERENCES users (id)
                                                  ON DELETE NO ACTION ON UPDATE NO ACTION,
                                          group_expense_id INTEGER NOT NULL
                                              CONSTRAINT fk_user_debts_group_expense
                                                  REFERENCES group_expenses (id)
                                                  ON DELETE NO ACTION ON UPDATE NO ACTION,
                                          status BOOLEAN
) INHERITS (auditable_entity);

CREATE TABLE IF NOT EXISTS group_members (
                                             id SERIAL PRIMARY KEY,
                                             user_id INTEGER NOT NULL
                                                 CONSTRAINT fk_group_members_user
                                                     REFERENCES users (id)
                                                     ON DELETE NO ACTION ON UPDATE NO ACTION,
                                             group_id INTEGER NOT NULL
                                                 CONSTRAINT fk_group_members_group
                                                     REFERENCES groups (id)
                                                     ON DELETE NO ACTION ON UPDATE NO ACTION,
                                             role group_member_role NOT NULL
) INHERITS (auditable_entity);

CREATE TABLE IF NOT EXISTS accounts (
                                        id SERIAL PRIMARY KEY,
                                        user_id INTEGER NOT NULL
                                            CONSTRAINT fk_accounts_user
                                                REFERENCES users (id)
                                                ON DELETE NO ACTION ON UPDATE NO ACTION,
                                        bank_id INTEGER NOT NULL
                                            CONSTRAINT fk_accounts_bank
                                                REFERENCES banks (id)
                                                ON DELETE NO ACTION ON UPDATE NO ACTION
) INHERITS (auditable_entity);

CREATE TABLE IF NOT EXISTS pix_keys (
                                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        pix_key TEXT NOT NULL UNIQUE,
                                        account_id INTEGER NOT NULL
                                            CONSTRAINT fk_pix_keys_account
                                                REFERENCES accounts (id)
                                                ON DELETE NO ACTION ON UPDATE NO ACTION,
                                        key_type pix_key_type NOT NULL
) INHERITS (auditable_entity);

CREATE TABLE IF NOT EXISTS payments (
                                        id SERIAL PRIMARY KEY,
                                        amount NUMERIC NOT NULL,
                                        transaction_date TIMESTAMP NOT NULL,
                                        user_debt_id INTEGER NOT NULL
                                            CONSTRAINT fk_payments_user_debt
                                                REFERENCES user_debts (id)
                                                ON DELETE NO ACTION ON UPDATE NO ACTION,
                                        proof TEXT
) INHERITS (auditable_entity);

COMMIT;